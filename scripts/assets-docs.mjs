// Generates ASSETS.md from assets.manifest.json.
// Usage: npm run assets:docs          (write)
//        npm run assets:docs -- --check  (CI: fail if ASSETS.md is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadManifest } from './lib/assets.mjs';

const m = loadManifest();
const out = path.join(ROOT, 'ASSETS.md');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const lic = `public/${m.roots.licensed}`, cc = `public/${m.roots.cc0}`, ph = `public/${m.roots.placeholder}`;

const groups = new Map();
for (const a of m.assets) {
  const g = a.key.split('.')[0];
  if (!groups.has(g)) groups.set(g, []);
  groups.get(g).push(a);
}
const TITLES = { hero: 'Hero skins (AWI slot: hero)', weapon: 'Weapons (AWI slot: weapon)', pet: 'Pets (AWI slot: pet)', trinket: 'Trinkets (AWI slot: trinket)', obj: 'World objects', enemy: 'Enemies', bg: 'Backgrounds', ui: 'HUD / UI', fx: 'Effects', sfx: 'Sound effects', music: 'Music' };

let md = `<!-- GENERATED by scripts/assets-docs.mjs from assets.manifest.json. Do not edit by hand: run \`npm run assets:docs\`. -->
# Art & sound assets

Altered Run is open source. Its art comes from three places:

- **CC0 packs (GameArt2D freebies):** public domain, so they are **committed** in \`${cc}/\`.
- **Other third-party packs (craftpix.net freebies):** free to use in games, but the files may **not be
  redistributed**, so you supply them yourself in \`${lic}/\` (gitignored).
- **Original placeholder art (MIT):** committed, used for anything not supplied above.

The items players carry are **AWIs (Altered World Items)**: NFTs mapped to in-game items through TheoSwap.
Each AWI slot (hero, weapon, pet, trinket) is drawn with the assets below.

## How it works

| Folder | In git? | What goes there |
|---|---|---|
| \`${lic}/\` | ❌ **gitignored** | Your copies of non-redistributable art, at the same relative paths. |
| \`${cc}/\` | ✅ committed | Art from sources marked \`"cc0": true\` in the manifest (only those). |
| \`${ph}/\` | ✅ committed | Original placeholder art (MIT), generated by \`npm run assets:placeholders\`. Same file names, pixel sizes and frame counts as the real art. |

For every entry in \`assets.manifest.json\`, the game loads the first of \`${lic}/<path>\`, \`${cc}/<path>\`
(CC0 sources only) and \`${ph}/<path>\` that **exists and has the exact pixel size listed below**.
A fresh clone runs right away on the committed CC0 art and placeholders. A file with the wrong size is
skipped with a warning, so it can't break the game.

## Dropping in the real art

1. **Download the packs** listed under *Sources* below (you need your own account/licence for each).
   Unzip them **outside** this repo, e.g. \`~/Downloads/altered-run-art/\`.
2. **Pack each asset into the expected file** with the helper. It sorts numbered frames, scales them uniformly
   to the frame size, aligns characters to the bottom edge, and writes a horizontal strip into \`${cc}/\` for
   CC0 sources or \`${lic}/\` for everything else:
   \`\`\`bash
   npm run assets:pack -- hero.ninja.run ~/Downloads/altered-run-art/ninja/png/Run__00*.png
   npm run assets:pack -- obj.crate ~/Downloads/altered-run-art/tileset/png/Object/Crate.png
   \`\`\`
   (You can also make the strips yourself in any editor: the table gives the exact size and frame layout.)
3. **Check what the game will use:** \`npm run assets:status\` lists every asset as ● licensed, ◆ cc0, ○ placeholder or ✖ missing,
   and flags wrong-size files.
4. **Run it:** \`npm run dev\`. The dev server reloads when files appear in either folder.
5. **Commit only \`${cc}/\`.** \`.gitignore\` excludes \`${lic}/\`, and \`npm run check-assets\` (pre-commit hook + CI)
   fails if a licensed file, or a non-CC0 file in \`${cc}/\`, is ever staged. If it fires: \`git rm --cached <file>\`.

Spritesheets are **one row of frames, left to right**, no padding: total width = frame width × frame count.
Art is authored at **2×** the game's logical size (\`displayScale\` 0.5) so it stays sharp on phones.

## Adding or changing an asset

Edit \`assets.manifest.json\` (key, path, size, frames, what it's for, source). If needed, add a drawer for the key in
\`scripts/placeholder-art.mjs\`. Then run \`npm run assets:placeholders && npm run assets:docs\` and commit the
manifest, the placeholder, and this file. Game code refers to assets **only by manifest key**.

## Every file to replace (${m.assets.length})
`;

for (const [g, list] of groups) {
  md += `\n### ${TITLES[g] ?? g}\n\n| Key | File (under \`${cc}/\` or \`${lic}/\`) | Size · frames | Used for | Get it from |\n|---|---|---|---|---|\n`;
  for (const a of list) {
    const s = m.sources[a.source];
    const size = a.type === 'audio' ? 'audio' : a.frameCount > 1
      ? `${a.width}×${a.height} · ${a.frameCount} × ${a.frameWidth}×${a.frameHeight}${a.animation?.frameRate ? ` @ ${a.animation.frameRate} fps` : ''}${a.animation?.repeat === -1 ? ', loop' : ''}`
      : `${a.width}×${a.height}${a.tile ? ' · tiles horizontally' : ''}`;
    const from = a.source === 'own' ? 'Original. Keep the placeholder.' : `${s.cc0 ? '**CC0** → \`cc0/\` ' : '→ \`licensed/\` '}[${s.name}](${s.url})${a.sourceFiles ? `<br>files: \`${a.sourceFiles}\`` : ''}`;
    md += `| \`${a.key}\` | \`${a.path}\` | ${esc(size)} | ${esc(a.usedFor)}${a.notes ? ` ${esc(a.notes)}` : ''} | ${from} |\n`;
  }
}

md += `\n## Sources\n\n| Id | Pack | Committed? | Licence note |\n|---|---|---|---|\n`;
for (const [k, s] of Object.entries(m.sources)) {
  const where = k === 'own' ? 'yes (placeholder)' : s.cc0 ? 'yes, in \`cc0/\`' : 'no, \`licensed/\`';
  md += `| \`${k}\` | [${esc(s.name)}](${s.url}) | ${where} | ${esc(s.licence)}${s.licenceUrl ? ` [Licence](${s.licenceUrl})` : ''} |\n`;
}
md += `\nPack names and file names are suggestions. Any art works if it matches the size and frame layout above.
Always read the licence on the pack's own page; the notes here are not legal advice.\n`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== md) { console.error('✖ ASSETS.md is out of date. Run: npm run assets:docs'); process.exit(1); }
  console.log('✔ ASSETS.md is up to date');
} else {
  fs.writeFileSync(out, md);
  console.log(`Wrote ASSETS.md (${m.assets.length} assets)`);
}
