import Phaser from 'phaser';
import { GAME_W, GAME_H, DEBUG } from './config';
import { BootScene } from './scenes/BootScene';
import { MenuScene } from './scenes/MenuScene';
import { RunScene } from './scenes/RunScene';
import { GameOverScene } from './scenes/GameOverScene';
import { ConnectScene } from './scenes/ConnectScene';
import { RevealScene } from './scenes/RevealScene';
import { LoadoutScene } from './scenes/LoadoutScene';
import { initAudio } from './systems/audio';
import './systems/install'; // listen for the browser's install prompt from the very first moment

const game = new Phaser.Game({
  type: Phaser.AUTO,
  parent: 'game',
  width: GAME_W,
  height: GAME_H,
  backgroundColor: '#0b1020',
  scale: { mode: Phaser.Scale.FIT, autoCenter: Phaser.Scale.CENTER_BOTH },
  render: { antialias: true, powerPreference: 'high-performance', roundPixels: false },
  fps: { target: 60, smoothStep: true },
  input: { activePointers: 2 },
  disableContextMenu: true,
  dom: { createContainer: true }, // the user-code text field on the Connect screen
  banner: false,
  audio: { noAudio: true }, // sound is our own Web Audio synth (src/systems/audio.ts)
  scene: [BootScene, MenuScene, ConnectScene, RevealScene, LoadoutScene, RunScene, GameOverScene],
});

initAudio();

// Offline play + "Add to Home Screen" (production builds only; sw.js is generated by vite.config.ts).
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => { navigator.serviceWorker.register('./sw.js').catch(() => { /* offline play is optional */ }); });
}

if (DEBUG) (window as unknown as { __game: Phaser.Game }).__game = game;
